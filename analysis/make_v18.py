"""
Generate models/AP_model_v18.py from AP_model_v17.py plus the fitted parameter
set produced by analysis/sensitivity_v17.py.

v18 = v17 with the identifiable parameters updated.  Rather than overwriting
v17's literals in place (which would erase the evidence of what actually
changed), the generated file keeps every v17 baseline visible and adds one
auditable FITTED block that is applied at the end of __init__.  Reading v18
therefore tells you both the literature value and the fitted value of every
parameter that moved, and why.

    python3 analysis/make_v18.py            # write models/AP_model_v18.py
    python3 analysis/make_v18.py --dry-run  # print the generated block only
"""

import argparse
import json
import os
import sys
from datetime import datetime

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from analysis import ap_cost as A
from project_paths import MODELS_DIR, RESULTS_SENSITIVITY_V17

SRC = os.path.join(MODELS_DIR, "AP_model_v17.py")
DST = os.path.join(MODELS_DIR, "AP_model_v18.py")
FIT = os.path.join(RESULTS_SENSITIVITY_V17, "fitted_parameters.json")


HEADER = '''"""
Fetal Cardiovascular Lumped Parameter Model - v18 (data-fitted parameters)
==================================================
v18 = v17 with every parameter the March 2024 ECMO recording can actually
constrain re-fitted against it.  Topology, state vector, mechanism equations
and toggles are IDENTICAL to v17 -- only parameter values differ.

GENERATED by analysis/make_v18.py on {date}.  Do not hand-edit: re-run the
pipeline instead, or the file will drift from its provenance record.

--------------------------------------------------------------------------
HOW THE PARAMETERS WERE CHOSEN
--------------------------------------------------------------------------
    analysis/ap_cost.py                 chi-square feature cost J (8 features)
    analysis/profile_likelihood_v17.py  which parameters are identifiable
    analysis/sensitivity_v17.py         joint re-fit of the identifiable ones
    analysis/make_v18.py                this file

v17 ran at {q17:.0f} mL/min mean AP flow against a clinical {qc:.0f}, because it
reverted the three circuit constants v16 had baked in.  Stage A of the profile
likelihood re-fitted those; stages B-C then established which of the 62
homeostatic mechanism parameters the data can constrain at all, and only those
were fitted.  Everything else is left at its v17 literature value ON PURPOSE:
a parameter the data cannot distinguish would be moved to an arbitrary value
by an optimiser, with no physiological justification and no reproducibility on
a different recording.

    cost before (v17 as written)   J = {j_v17:.2f}
    cost after  (circuit re-fit)   J = {j_circ:.2f}
    cost after  (this file)        J = {j_fit:.2f}

Confidence intervals, verdicts and the full parameter ranking are in
    results/profile_likelihood_v17/profile_summary.csv
    results/profile_likelihood_v17/profile_likelihood_grid.png
    results/sensitivity_v17/fitted_parameters.json

--------------------------------------------------------------------------
WHAT MOVED
--------------------------------------------------------------------------
{moved}

--------------------------------------------------------------------------
WHAT DELIBERATELY DID NOT MOVE
--------------------------------------------------------------------------
{unmoved}

--------------------------------------------------------------------------
v17's ORIGINAL HEADER (topology, mechanisms, references) follows
--------------------------------------------------------------------------
{v17_header}
"""'''


FITTED_BLOCK = '''

# ╔══════════════════════════════════════════════════════════════════╗
# ║  FITTED PARAMETERS  (v18)                                        ║
# ╚══════════════════════════════════════════════════════════════════╝
# Produced by analysis/sensitivity_v17.py against
# data/ECMO_Trial_2024-03-05_cleaned_v2.csv, window {win}.
# Applied at the END of ArtificialPlacentaModel.__init__, so every v17
# baseline literal above stays readable and the diff is explicit.
#
# Each entry: name -> (fitted value, v17 value, verdict, 95% CI)
FITTED = {{
{entries}
}}

# Parameters the profile likelihood proved the data cannot constrain are NOT
# listed here; they keep their v17 literature values.  See the module header.

FITTED_PROVENANCE = {{
    "generated":   "{date}",
    "source":      "analysis/sensitivity_v17.py",
    "cost_before": {j_circ!r},
    "cost_after":  {j_fit!r},
    "objective":   "chi-square over {nfeat} features, {simdur:.0f} s sim, last {ansec:.0f} s scored",
}}
'''


APPLY_METHOD = '''
    # ──────────────────────────────────────────────────────────────
    #  v18: APPLY THE FITTED PARAMETER SET
    # ──────────────────────────────────────────────────────────────
    def _apply_fitted(self):
        """Overwrite the v17 baselines with the fitted values in FITTED.

        Called at the end of __init__.  R['AO4_UA'] and C['UA'] need special
        handling because they also live in R_baseline and c_list, which the
        mechanism code reads from.
        """
        for name, (value, _v17, _verdict, _ci) in FITTED.items():
            if name == "R_AO4_UA":
                self.R["AO4_UA"] = float(value)
                self.R_baseline["AO4_UA"] = float(value)
            elif name == "C_UA":
                self.C["UA"] = float(value)
                self.c_list = [self.C[k] for k in self._c_keys]
            elif name == "V_BLOOD_TOTAL":
                pass                      # applied via the BLOOD_VOLUME constant
            elif name == "Vu_frac_global":
                for k in self.Vu_frac:
                    self.Vu_frac[k] = float(value)
            else:
                setattr(self, name, float(value))
'''


def fmt_ci(ci_lo, ci_hi):
    if ci_lo is None and ci_hi is None:
        return "unbounded"
    lo = "-inf" if ci_lo is None else f"{ci_lo:.4g}"
    hi = "+inf" if ci_hi is None else f"{ci_hi:.4g}"
    return f"[{lo}, {hi}]"


def build(fit, state, dry_run=False):
    ref = fit["reference"]
    fitted = fit["fitted"]
    sel = {s["name"]: s for s in fit["selection"]}

    src = open(SRC).read()

    # ---- header ----------------------------------------------------------
    v17_header = src[src.index('"""') + 3: src.index('"""', 3)].strip()
    q17, qc = fit.get("q_v17", 418.5), fit.get("q_clinical", 188.4)

    moved_lines = []
    for name in fit["fitted_names"]:
        s = sel.get(name)
        v = fitted[name]
        r = ref[name]
        pct = (v / r - 1) * 100 if abs(r) > 1e-12 else float("nan")
        tag = ("circuit" if name in A.CIRCUIT_PARAMS
               else f"{s['mech']}, {s['verdict']}")
        ci = "" if name in A.CIRCUIT_PARAMS else f"  95% CI {fmt_ci(s['ci_lo'], s['ci_hi'])}"
        moved_lines.append(
            f"  {name:<22} {r:>13.6g}  ->  {v:<13.6g} "
            f"({pct:+7.1f}%)   [{tag}]{ci}")

    rows = state_rows(state)
    unmoved = []
    n_struct = sum(1 for r in rows if r["verdict"] == "structural")
    n_prac   = sum(1 for r in rows if r["verdict"] == "practical")
    unmoved.append(
        f"  {n_struct} of {len(rows)} mechanism parameters are STRUCTURALLY "
        f"non-identifiable against this\n  30 s recording -- the cost is flat "
        f"in them, so no value is better supported than any other.")
    slow = [r["name"] for r in rows
            if r["verdict"] == "structural" and r["mech"] in
            ("edema", "regurgitation", "raas", "vasopressin", "catecholamine")]
    if slow:
        unmoved.append(
            f"\n  Most are the slow mechanisms, and this is expected rather than a "
            f"failure:\n  edema_tau = 36000 s, regurg_tau = 36000 s, raas_tau = 3600 s and\n"
            f"  avp_tau = 1800 s cannot express themselves inside a "
            f"{A.SIM_DURATION:.0f} s simulation.\n  Constraining them needs a "
            f"recording hours long, not this one.")
    inert = [r["name"] for r in rows if r["verdict"] == "structural"
             and r["mech"] == "baroreflex" and "Vu" in r["name"]]
    if inert:
        unmoved.append(
            f"\n  {', '.join(inert)} are inert for a second reason: v17 ships every\n"
            f"  Vu_frac entry at 0.0, which makes the unstressed volume "
            f"identically zero and\n  the venous-tone baroreflex arm a no-op "
            f"regardless of its gain or time constant.")
    unmoved.append(
        f"\n  {n_prac} more are only PRACTICALLY identifiable (bounded on one "
        f"side only).\n  Those among the top {len(fit['mechanism_names'])} by "
        f"profile depth were still fitted, but their\n  values should be read "
        f"as a bound, not a measurement.")

    header = HEADER.format(
        date=datetime.now().strftime("%Y-%m-%d"),
        q17=q17, qc=qc,
        j_v17=fit.get("cost_v17_as_written", float("nan")),
        j_circ=fit["cost_before"], j_fit=fit["cost_after"],
        moved="\n".join(moved_lines),
        unmoved="\n".join(unmoved),
        v17_header=v17_header)

    # ---- fitted block ----------------------------------------------------
    entries = []
    for name in fit["fitted_names"]:
        s = sel.get(name)
        verdict = "circuit-nuisance" if s is None else s["verdict"]
        ci = "n/a" if s is None else fmt_ci(s["ci_lo"], s["ci_hi"])
        entries.append(
            f'    {name!r:<24}: ({fitted[name]!r}, {ref[name]!r}, '
            f'{verdict!r}, {ci!r}),')

    block = FITTED_BLOCK.format(
        win=f"{A.START_TIME}-{A.END_TIME}",
        entries="\n".join(entries),
        date=datetime.now().isoformat(timespec="seconds"),
        j_circ=fit["cost_before"], j_fit=fit["cost_after"],
        nfeat=len(A.FEATURES), simdur=A.SIM_DURATION, ansec=A.ANALYSIS_SECONDS)

    if dry_run:
        print(header)
        print(block)
        return None

    # ---- assemble --------------------------------------------------------
    body = src[src.index('"""', 3) + 3:]

    # BLOOD_VOLUME: the fitted total, replacing v17's 70 mL
    old_bv = "BLOOD_VOLUME = 70   # mL — fetal blood (~55 mL/kg × 0.6 kg) + circuit priming"
    if old_bv not in body:
        raise RuntimeError("BLOOD_VOLUME line not found in v17 -- generator is stale.")
    new_bv = (f"BLOOD_VOLUME = {fitted['V_BLOOD_TOTAL']!r}   "
              f"# mL — FITTED (v17: 70; v16: 268.787). Total circuit volume.")
    body = body.replace(old_bv, new_bv, 1)

    # Insert the FITTED table right after the AP_RL / dPump section
    anchor = "# ╔══════════════════════════════════════════════════════════════════╗\n# ║  STATE VECTOR INDEX MAP"
    if anchor not in body:
        raise RuntimeError("state-vector anchor not found -- generator is stale.")
    body = body.replace(anchor, block.rstrip() + "\n\n\n" + anchor, 1)

    # Call _apply_fitted at the end of __init__ (just before ap_loop)
    tail_anchor = ("    # ──────────────────────────────────────────────────────────────\n"
                   "    #  AP CIRCUIT DYNAMICS")
    if tail_anchor not in body:
        raise RuntimeError("ap_loop anchor not found -- generator is stale.")
    body = body.replace(
        tail_anchor,
        "        # ── v18: apply the fitted parameter set ──────────────────\n"
        "        self._apply_fitted()\n"
        + APPLY_METHOD + "\n" + tail_anchor, 1)

    # v16 -> v18 in the plot title and class banner
    body = body.replace("LPM v16 vs Clinical", "LPM v18 vs Clinical")
    body = body.replace("║  FETAL CARDIOVASCULAR MODEL  v16", "║  FETAL CARDIOVASCULAR MODEL  v18")

    out = header + body
    with open(DST, "w") as f:
        f.write(out)
    print(f"wrote {DST}  ({len(out.splitlines())} lines)")
    return DST


def state_rows(state):
    from analysis import profile_likelihood_v17 as PL
    return PL.summary_rows(state)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    if not os.path.isfile(FIT):
        print(f"missing {FIT}\nRun: python3 analysis/sensitivity_v17.py")
        return
    with open(FIT) as f:
        fit = json.load(f)

    from analysis import profile_likelihood_v17 as PL
    state = PL.load_state()
    if not state.get("scan"):
        print("missing profile likelihood state; run profile_likelihood_v17.py")
        return

    build(fit, state, dry_run=args.dry_run)


if __name__ == "__main__":
    main()
